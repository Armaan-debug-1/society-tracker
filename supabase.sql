-- Complete Database Schema for Society Tracker (Secured with Supabase Auth)
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 1. Profiles Table (replaces custom_users for auth, but keeps profile data)
CREATE TABLE IF NOT EXISTS public.custom_users (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT UNIQUE NOT NULL,
    role TEXT[] DEFAULT '{"MEMBER-1"}',
    full_name TEXT,
    contact TEXT,
    gender TEXT,
    association TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Drop obsolete password column if it exists from previous custom implementations
ALTER TABLE public.custom_users DROP COLUMN IF EXISTS password;

-- 2. Channel Tasks
CREATE TABLE IF NOT EXISTS public.channel_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name TEXT,
    channel_name TEXT,
    title TEXT,
    priority TEXT,
    deadline TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Notices
CREATE TABLE IF NOT EXISTS public.notices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_name TEXT,
    content TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. My Tasks
CREATE TABLE IF NOT EXISTS public.my_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES public.custom_users(id) ON DELETE CASCADE,
    name TEXT,
    description TEXT,
    priority INTEGER DEFAULT 1,
    deadline_date TEXT,
    deadline_time TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- =============================================================================
-- ROW LEVEL SECURITY POLICIES
-- =============================================================================

ALTER TABLE public.custom_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.channel_tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notices ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.my_tasks ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if they exist (to avoid errors)
DROP POLICY IF EXISTS "Allow all access to custom_users" ON public.custom_users;
DROP POLICY IF EXISTS "Allow all access to channel_tasks" ON public.channel_tasks;
DROP POLICY IF EXISTS "Allow all access to notices" ON public.notices;
DROP POLICY IF EXISTS "Allow all access to my_tasks" ON public.my_tasks;

DROP POLICY IF EXISTS "Authenticated users can read profiles" ON public.custom_users;
DROP POLICY IF EXISTS "Users can update own profile" ON public.custom_users;
DROP POLICY IF EXISTS "Admins can update any profile" ON public.custom_users;
DROP POLICY IF EXISTS "Authenticated users full access to channel_tasks" ON public.channel_tasks;
DROP POLICY IF EXISTS "Authenticated users full access to notices" ON public.notices;
DROP POLICY IF EXISTS "Users can only access their own tasks" ON public.my_tasks;

-- Profiles (custom_users)
-- Anyone authenticated can read profiles
CREATE POLICY "Authenticated users can read profiles" ON public.custom_users FOR SELECT USING (auth.role() = 'authenticated');
-- Users can update their own profile
CREATE POLICY "Users can update own profile" ON public.custom_users FOR UPDATE USING (id = auth.uid());
-- Admins can update any profile (e.g. changing roles)
CREATE POLICY "Admins can update any profile" ON public.custom_users FOR UPDATE USING (
  EXISTS (SELECT 1 FROM public.custom_users WHERE id = auth.uid() AND 'ADMIN' = ANY(role))
);

-- Tasks & Notices
CREATE POLICY "Authenticated users full access to channel_tasks" ON public.channel_tasks FOR ALL USING (auth.role() = 'authenticated');
CREATE POLICY "Authenticated users full access to notices" ON public.notices FOR ALL USING (auth.role() = 'authenticated');

-- My Tasks (Global visibility and access for all users as requested)
CREATE POLICY "Users can access all tasks" ON public.my_tasks FOR ALL USING (auth.role() = 'authenticated');

