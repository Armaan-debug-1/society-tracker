-- Function to create initial admin or reset admin if needed
CREATE OR REPLACE FUNCTION setup_initial_admin(admin_email TEXT, admin_password TEXT)
RETURNS void
SECURITY DEFINER
AS $$
DECLARE
  new_id UUID := gen_random_uuid();
  existing_id UUID;
BEGIN
  -- Check if user exists in auth.users
  SELECT id INTO existing_id FROM auth.users WHERE email = admin_email;
  
  IF existing_id IS NULL THEN
    -- Check if the email is already in custom_users
    SELECT id INTO existing_id FROM public.custom_users WHERE email = admin_email;
    IF existing_id IS NOT NULL THEN
      new_id := existing_id;
    END IF;

    -- Insert into auth.users directly (without instance_id to avoid schema errors)
    INSERT INTO auth.users (
      id, aud, role, email, encrypted_password, email_confirmed_at, 
      raw_app_meta_data, raw_user_meta_data, created_at, updated_at
    )
    VALUES (
      new_id, 'authenticated', 'authenticated', 
      admin_email, crypt(admin_password, gen_salt('bf')), now(),
      '{"provider":"email","providers":["email"]}', '{}', now(), now()
    );

    -- Create profile for admin
    INSERT INTO public.custom_users (id, email, role, full_name)
    VALUES (new_id, admin_email, '{"ADMIN"}', 'System Admin')
    ON CONFLICT (email) DO UPDATE SET role = '{"ADMIN"}', id = EXCLUDED.id;
  END IF;
END;
$$ LANGUAGE plpgsql;

-- Execute to create the default admin user
SELECT setup_initial_admin('admin@society.com', 'admin123');

-- RPC for AdminPanel to add a new user
CREATE OR REPLACE FUNCTION admin_add_user(new_email TEXT, new_password TEXT, new_roles TEXT[])
RETURNS UUID
SECURITY DEFINER
AS $$
DECLARE
  new_user_id UUID;
  is_admin BOOLEAN;
  existing_id UUID;
BEGIN
  -- Verify caller is admin
  SELECT EXISTS (
    SELECT 1 FROM public.custom_users 
    WHERE id = auth.uid() AND 'ADMIN' = ANY(role)
  ) INTO is_admin;

  IF NOT is_admin THEN
    RAISE EXCEPTION 'Access Denied: Only Admins can create users.';
  END IF;

  SELECT id INTO existing_id FROM auth.users WHERE email = new_email;
  IF existing_id IS NOT NULL THEN
    RAISE EXCEPTION 'User with this email already exists.';
  END IF;

  SELECT id INTO existing_id FROM public.custom_users WHERE email = new_email;
  IF existing_id IS NOT NULL THEN
     new_user_id := existing_id;
  ELSE
     new_user_id := gen_random_uuid();
  END IF;

  INSERT INTO auth.users (
    id, aud, role, email, encrypted_password, email_confirmed_at, 
    raw_app_meta_data, raw_user_meta_data, created_at, updated_at
  )
  VALUES (
    new_user_id, 'authenticated', 'authenticated', 
    new_email, crypt(new_password, gen_salt('bf')), now(),
    '{"provider":"email","providers":["email"]}', '{}', now(), now()
  );

  INSERT INTO public.custom_users (id, email, role)
  VALUES (new_user_id, new_email, new_roles)
  ON CONFLICT (email) DO UPDATE SET role = EXCLUDED.role, id = EXCLUDED.id;

  RETURN new_user_id;
END;
$$ LANGUAGE plpgsql;

-- RPC for AdminPanel to delete a user securely
CREATE OR REPLACE FUNCTION admin_delete_user(target_user_id UUID)
RETURNS void
SECURITY DEFINER
AS $$
DECLARE
  is_admin BOOLEAN;
BEGIN
  -- Verify caller is admin
  SELECT EXISTS (
    SELECT 1 FROM public.custom_users 
    WHERE id = auth.uid() AND 'ADMIN' = ANY(role)
  ) INTO is_admin;

  IF NOT is_admin THEN
    RAISE EXCEPTION 'Access Denied: Only Admins can delete users.';
  END IF;

  -- Delete from auth.users (cascades to custom_users)
  DELETE FROM auth.users WHERE id = target_user_id;
END;
$$ LANGUAGE plpgsql;
